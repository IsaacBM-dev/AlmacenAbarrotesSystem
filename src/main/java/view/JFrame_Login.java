    /**
     * Método que valida las credenciales ingresadas en jtf_username y jtf_password
     */
    private void autenticar() {
        String username = jtf_username.getText().trim();
        String password = jpf_password.getText();

        String resultado = usuarioController.login(username, password);

        if ("OK".equals(resultado)) {
            JFrame_Principal ventanaPrincipal = new JFrame_Principal();
            ventanaPrincipal.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, resultado, "Acceso Denegado", JOptionPane.WARNING_MESSAGE);
            jpf_password.setText("");
            jpf_password.requestFocus();
        }
    }
    
    
